#!/bin/sh

# Regenerates requirements.lock from the pinned Aerodrome release's requirements.
# Run it when the build reports that the lock no longer satisfies them.

set -eu

pip_tools_version=7.6.2
ref=$(sed -n 's/^ARG AERODROME_REF=//p' Dockerfile)
if [ -z "$ref" ]; then
    echo "Could not read AERODROME_REF from the Dockerfile." >&2
    exit 1
fi

temporary=$(mktemp requirements.lock.XXXXXX)
trap 'rm -f "$temporary"' EXIT

# shellcheck disable=SC2016 # Expanded by the shell inside the container.
docker run --rm \
    --env "AERODROME_REF=$ref" \
    --env "PIP_TOOLS_VERSION=$pip_tools_version" \
    --entrypoint sh \
    dhi.io/python:3.14-debian13-dev \
    -c '
        set -eu
        cd /tmp
        python -m venv tools
        tools/bin/pip install --quiet "pip-tools==$PIP_TOOLS_VERSION"
        python -c "import os, urllib.request; urllib.request.urlretrieve(\"https://raw.githubusercontent.com/preston-peterson/aerodrome/\" + os.environ[\"AERODROME_REF\"] + \"/requirements.txt\", \"requirements.txt\")"
        tools/bin/pip-compile --quiet --generate-hashes --allow-unsafe --strip-extras --no-emit-index-url --no-header --output-file=- requirements.txt
    ' > "$temporary"

{
    echo "# Generated by scripts/update-lock.sh from Aerodrome's requirements.txt."
    cat "$temporary"
} > requirements.lock

echo "Updated requirements.lock for Aerodrome $ref"
